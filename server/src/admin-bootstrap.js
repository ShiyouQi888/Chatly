import { hashPassword, verifyPassword } from './auth.js'
import { q, insert, tx, DB_DRIVER } from './db.js'

// Admin identities, sessions and audit records belong to their own account domain.
export async function bootstrapAdmin() {
  const identity = DB_DRIVER === 'sqlite' ? 'INTEGER PRIMARY KEY AUTOINCREMENT' : 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
  await q.run(`CREATE TABLE IF NOT EXISTS admin_accounts (
    id ${identity}, username TEXT NOT NULL, password_hash TEXT NOT NULL,
    nickname TEXT NOT NULL, role TEXT NOT NULL CHECK (role IN ('owner','moderator','support','analyst')),
    is_active INTEGER NOT NULL DEFAULT 1, created_by INTEGER REFERENCES admin_accounts(id) ON DELETE SET NULL,
    bootstrap_username TEXT, bootstrap_password_hash TEXT, legacy_user_id INTEGER UNIQUE,
    created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL
  )`)
  await q.run('CREATE UNIQUE INDEX IF NOT EXISTS idx_admin_accounts_username ON admin_accounts(lower(username))')
  await q.run("CREATE UNIQUE INDEX IF NOT EXISTS idx_admin_accounts_owner ON admin_accounts(role) WHERE role = 'owner'")
  await q.run(`CREATE TABLE IF NOT EXISTS admin_sessions (
    token_hash TEXT PRIMARY KEY, account_id INTEGER NOT NULL REFERENCES admin_accounts(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL
  )`)
  await q.run('CREATE INDEX IF NOT EXISTS idx_admin_sessions_account ON admin_sessions(account_id)')
  await q.run(`CREATE TABLE IF NOT EXISTS admin_operation_logs (
    id ${identity}, admin_id INTEGER REFERENCES admin_accounts(id) ON DELETE SET NULL,
    admin_username TEXT, admin_nickname TEXT, action TEXT NOT NULL, target_type TEXT NOT NULL,
    target_id INTEGER, detail TEXT, created_at BIGINT NOT NULL, legacy_log_id INTEGER UNIQUE
  )`)
  await q.run('CREATE INDEX IF NOT EXISTS idx_admin_operations_created ON admin_operation_logs(created_at DESC)')
  await q.run('CREATE TABLE IF NOT EXISTS admin_auth_meta (name TEXT PRIMARY KEY, value TEXT NOT NULL)')
  for (const [table, column] of [['users', 'banned_by_admin'], ['feedbacks', 'handled_by_admin']]) {
    try { await q.run(`ALTER TABLE ${table} ADD COLUMN ${column} INTEGER REFERENCES admin_accounts(id) ON DELETE SET NULL`) }
    catch (error) { if (!/duplicate column|already exists/i.test(error.message || '')) throw error }
  }

  // Copy old credentials once; future user sessions cannot access management APIs.
  if (!await q.get("SELECT 1 FROM admin_auth_meta WHERE name = 'independent-accounts-v1'")) {
    await tx(async () => {
      const legacyRoot = await q.get('SELECT * FROM admin_root WHERE singleton = 1')
      const root = legacyRoot ? await q.get('SELECT * FROM users WHERE id = ?', legacyRoot.user_id) : null
      const now = Date.now()
      if (root && !await q.get("SELECT id FROM admin_accounts WHERE role = 'owner'")) {
        await insert(`INSERT INTO admin_accounts (username, password_hash, nickname, role, legacy_user_id, bootstrap_username, bootstrap_password_hash, created_at, updated_at)
          VALUES (?, ?, ?, 'owner', ?, ?, ?, ?, ?)`, root.username, root.password_hash, root.nickname, root.id, legacyRoot.bootstrap_username || null, legacyRoot.bootstrap_password_hash || null, now, now)
      }
      const staff = await q.all('SELECT u.*, s.role, s.created_at AS granted_at FROM admin_staff s JOIN users u ON u.id = s.user_id')
      for (const member of staff) {
        if (await q.get('SELECT id FROM admin_accounts WHERE legacy_user_id = ? OR lower(username) = lower(?)', member.id, member.username)) continue
        await insert(`INSERT INTO admin_accounts (username, password_hash, nickname, role, is_active, legacy_user_id, created_at, updated_at)
          VALUES (?, ?, ?, ?, ?, ?, ?, ?)`, member.username, member.password_hash, member.nickname, member.role, member.is_banned ? 0 : 1, member.id, Number(member.granted_at) || now, now)
      }
      await q.run(`INSERT INTO admin_operation_logs (admin_username, admin_nickname, action, target_type, target_id, detail, created_at, legacy_log_id)
        SELECT u.username, u.nickname, l.action, l.target_type, l.target_id, l.detail, l.created_at, l.id
        FROM admin_audit_logs l LEFT JOIN users u ON u.id = l.admin_id
        WHERE NOT EXISTS (SELECT 1 FROM admin_operation_logs migrated WHERE migrated.legacy_log_id = l.id)`)
      await q.run("INSERT INTO admin_auth_meta (name, value) VALUES ('independent-accounts-v1', 'done')")
    })
  }

  const username = String(process.env.ADMIN_USERNAME || '').trim()
  const password = String(process.env.ADMIN_PASSWORD || '')
  if (Boolean(username) !== Boolean(password)) throw new Error('ADMIN_USERNAME 和 ADMIN_PASSWORD 必须同时配置')
  if (!username) return
  if (username.length < 2 || username.length > 128) throw new Error('ADMIN_USERNAME 长度必须为 2 到 128 个字符')
  if (password.length < 12 || password.length > 128) throw new Error('管理员密码必须为 12 到 128 个字符')
  if (/replace[-_ ]?with|change[-_ ]?me/i.test(password)) throw new Error('请先将 ADMIN_PASSWORD 示例值替换为强密码')
  const owner = await q.get("SELECT * FROM admin_accounts WHERE role = 'owner'")
  if (owner?.bootstrap_username === username && verifyPassword(password, owner.bootstrap_password_hash)) return
  const duplicate = await q.get('SELECT id FROM admin_accounts WHERE lower(username) = lower(?) AND id != ?', username, owner?.id || 0)
  if (duplicate) throw new Error('ADMIN_USERNAME 已被其他后台成员使用，请换一个后台账号')
  const hash = hashPassword(password)
  const nickname = String(process.env.ADMIN_NICKNAME || '运营管理员').slice(0, 40)
  await tx(async () => {
    if (owner) {
      await q.run('UPDATE admin_accounts SET username = ?, password_hash = ?, nickname = ?, bootstrap_username = ?, bootstrap_password_hash = ?, is_active = 1, updated_at = ? WHERE id = ?', username, hash, nickname, username, hash, Date.now(), owner.id)
      await q.run('DELETE FROM admin_sessions WHERE account_id = ?', owner.id)
    } else {
      await insert(`INSERT INTO admin_accounts (username, password_hash, nickname, role, bootstrap_username, bootstrap_password_hash, created_at, updated_at)
        VALUES (?, ?, ?, 'owner', ?, ?, ?, ?)`, username, hash, nickname, username, hash, Date.now(), Date.now())
    }
  })
  console.log('[admin] 独立后台管理员已初始化/更新')
}
